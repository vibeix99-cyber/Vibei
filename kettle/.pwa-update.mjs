import { chromium } from 'playwright';
import { appendFileSync } from 'node:fs';
const b = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
const ctx = await b.newContext();
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('[pageerror]', e.message.slice(0, 200)));
await p.goto('http://127.0.0.1:5183/?debug#/');
await p.evaluate(() => navigator.serviceWorker.ready);
await p.waitForTimeout(1500);
console.log('v1', JSON.stringify(await p.evaluate(() => window.__kettle.pwa.state())));
await p.evaluate(() => window.__kettle.timer.getState().startFocus({ minutes: 5 }));
const sid = await p.evaluate(() => window.__kettle.timer.getState().sessionId);
// Ship "v2": a byte-different service worker.
appendFileSync('/tmp/claude-0/-home-user-Vibei/af90140e-0279-5682-99d5-a47623d3eed0/scratchpad/dist/sw.js', '\n// v2\n');
await p.evaluate(async () => { const r = await navigator.serviceWorker.getRegistration(); await r.update(); });
await p.waitForFunction(() => window.__kettle.pwa.state().needRefresh, null, { timeout: 15000 });
console.log('after deploy', JSON.stringify(await p.evaluate(() => window.__kettle.pwa.state())), 'waiting?', await p.evaluate(async () => !!(await navigator.serviceWorker.getRegistration()).waiting));
console.log('still running (no auto reload):', await p.evaluate(() => window.__kettle.timer.getState().status));
const nav = p.waitForNavigation({ timeout: 15000 });
await p.evaluate(() => window.__kettle.pwa.update());
await nav;
await p.waitForFunction(() => !!window.__kettle?.timerInfo);
await p.waitForTimeout(800);
console.log('after update: waiting?', await p.evaluate(async () => !!(await navigator.serviceWorker.getRegistration()).waiting), 'same session running:', await p.evaluate((sid) => window.__kettle.timer.getState().sessionId === sid && window.__kettle.timer.getState().status, sid));
await b.close();
