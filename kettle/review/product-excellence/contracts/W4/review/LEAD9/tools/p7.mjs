// Offline: SW active + precache, then network offline, reload, Stage animates with Rive. Also logs any CDN request.
import { chromium, OUT, CDN, boot, state } from './common.mjs';
import fs from 'node:fs';
const base = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const all = []; ctx.on('request', (r) => all.push([r.url(), !!r.serviceWorker()]));
const page = await ctx.newPage();
await page.goto(`${base}/?debug&seed=veteran#/`);
const poll = async (fn) => { for (let i = 0; i < 120; i++) { if (await page.evaluate(fn)) return true; await page.waitForTimeout(500); } throw new Error('poll timeout'); };
await poll(async () => { const r = await navigator.serviceWorker?.getRegistration(); return !!r?.active; });
await poll(async () => { const ks = await caches.keys(); for (const k of ks) { const c = await caches.open(k); const ks2 = (await c.keys()).map((r) => r.url); if (ks2.some((u) => /rive-.*\.wasm/.test(u)) && ks2.some((u) => /chai-.*\.riv/.test(u)) && ks2.some((u) => /riveChai-.*\.js/.test(u))) return true; } return false; });
await page.reload(); await poll(() => !!navigator.serviceWorker.controller);
const cached = await page.evaluate(async () => { const out = []; for (const k of await caches.keys()) { const c = await caches.open(k); out.push(...(await c.keys()).map((r) => r.url).filter((u) => /rive|\.riv|\.wasm/.test(u))); } return out; });
console.log('precached', cached);
await ctx.setOffline(true);
const mark = all.length;
await boot(page, base);
console.log('controller', await page.evaluate(() => !!navigator.serviceWorker.controller), 'online?', await page.evaluate(() => navigator.onLine));
await page.getByRole('button', { name: /put the kettle on/i }).first().click();
await page.waitForFunction(() => location.hash === '#/focus'); await page.waitForTimeout(4000);
const s1 = await state(page); await page.waitForTimeout(700); const s2 = await state(page);
const d1 = await page.evaluate(() => document.querySelector('[data-stage-figure=chai] canvas')?.toDataURL().length);
await page.waitForTimeout(1500);
const d2 = await page.evaluate(() => document.querySelector('[data-stage-figure=chai] canvas')?.toDataURL());
const d3 = await page.evaluate(() => document.querySelector('[data-stage-figure=chai] canvas')?.toDataURL());
await page.screenshot({ path: `${OUT}/offline-stage.png` });
const after = all.slice(mark);
const res = { cached, s1, s2, canvasChanged: d1 !== d2?.length || d2 !== d3, offlineRiveReqs: after.filter(([u]) => /rive|\.riv|wasm/.test(u)), cdn: all.filter(([u]) => CDN.test(u)) };
console.log(JSON.stringify(res, null, 1));
fs.writeFileSync(`${OUT}/p7-offline.json`, JSON.stringify(res, null, 1));
await b.close();
