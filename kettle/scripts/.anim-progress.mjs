import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
page.on('pageerror', (e) => console.log('[pageerror]', e.message.slice(0, 300)));
await page.goto('http://127.0.0.1:5186/?debug&seed=veteran&theme=light&motion=full#/', { waitUntil: 'networkidle' });
await page.waitForTimeout(800);
await page.evaluate(() => __kettle.navigate('/stats'));
await page.waitForTimeout(260);
await page.evaluate(() => document.querySelector('figure')?.scrollIntoView({ block: 'center' }));
await page.screenshot({ path: '.shots/progress/anim-0.png' });
await page.waitForTimeout(900);
await page.screenshot({ path: '.shots/progress/anim-1.png' });
await browser.close();
