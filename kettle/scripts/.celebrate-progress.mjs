import { chromium } from 'playwright';
const [,, base] = process.argv;
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader', '--use-angle=swiftshader'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const events = [];
page.on('console', (m) => { if (m.type() === 'error') console.log('[console.error]', m.text().slice(0, 300)); });
page.on('pageerror', (e) => console.log('[pageerror]', e.message.slice(0, 400)));
await page.goto(`${base}/?debug&seed=celebrate&theme=light&motion=reduce#/`, { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
await page.screenshot({ path: '.shots/progress/celebrate-home.png' });
await page.evaluate(() => { window.__ev = []; });
await page.evaluate(() => __kettle.timer.getState().startFocus());
await page.waitForTimeout(800);
await page.evaluate(() => __kettle.finish());
await page.waitForTimeout(3000);
const r = await page.evaluate(() => { const r = __kettle.progress.getState().lastReport; return r && { total: r.leaves.total, bonuses: r.leaves.bonuses.map((b) => `${b.label} +${b.amount}`), goal: r.goal, streak: { ...r.streak, week: r.streak.week.map((d) => d.label + ':' + d.state).join(' ') }, level: r.level, quests: r.quests.map((q) => `${q.title} ${q.before}->${q.after}/${q.target}${q.justCompleted ? ' DONE' : ''}`), badges: r.badges.map((b) => `${b.id} ${b.tier}`), all: r.allQuestsJustDone }; });
console.log(JSON.stringify(r, null, 1));
console.log('route', await page.evaluate(() => location.hash));
await page.screenshot({ path: '.shots/progress/celebrate-done.png' });
await page.goto(`${base}/?debug&seed=atRisk&theme=light&motion=reduce#/stats`, { waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
console.log('atRisk', await page.evaluate(() => [new Date(__kettle.clock.now()).toString(), document.querySelector('[class*=streakLine]')?.textContent]));
await page.screenshot({ path: '.shots/progress/atrisk-stats.png' });
await browser.close();
